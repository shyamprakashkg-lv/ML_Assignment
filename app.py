"""
Streamlit app for exploring the Telco Customer Churn models trained by
train.py. Upload the test_data.csv produced by the training script, pick a
model, and the app applies the saved preprocessing pipeline, scores the
data, and displays evaluation metrics, a confusion matrix, and a
classification report.
"""

import joblib
import matplotlib.pyplot as plt
import pandas as pd
import seaborn as sns
import streamlit as st
from sklearn.metrics import (
    accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    matthews_corrcoef,
    precision_score,
    recall_score,
    roc_auc_score,
)

MODEL_DIR = "model"
TARGET_COLUMN = "Churn"

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbor": "knn.joblib",
    "Gaussian Naive Bayes": "naive_bayes.joblib",
    "Random Forest": "random_forest.joblib",
}

st.set_page_config(page_title="Telco Customer Churn Classifier", layout="wide")


@st.cache_resource
def load_preprocessing_objects():
    scaler = joblib.load(f"{MODEL_DIR}/scaler.joblib")
    encoders = joblib.load(f"{MODEL_DIR}/encoders.joblib")
    target_encoder = joblib.load(f"{MODEL_DIR}/target_encoder.joblib")
    feature_columns = joblib.load(f"{MODEL_DIR}/feature_columns.joblib")
    numeric_columns = joblib.load(f"{MODEL_DIR}/numeric_columns.joblib")
    return scaler, encoders, target_encoder, feature_columns, numeric_columns


@st.cache_resource
def load_model(model_filename):
    return joblib.load(f"{MODEL_DIR}/{model_filename}")


def preprocess(df, encoders, scaler, feature_columns, numeric_columns):
    df = df.copy()

    if "customerID" in df.columns:
        df = df.drop(columns=["customerID"])

    df["TotalCharges"] = pd.to_numeric(df["TotalCharges"], errors="coerce")
    df["TotalCharges"] = df["TotalCharges"].fillna(df["TotalCharges"].median())
    df["SeniorCitizen"] = df["SeniorCitizen"].astype(str)

    for column, encoder in encoders.items():
        df[column] = encoder.transform(df[column])

    df[numeric_columns] = scaler.transform(df[numeric_columns])

    return df[feature_columns]


def main():
    st.title("Telco Customer Churn - Model Evaluation")
    st.write(
        "Upload the test_data.csv generated by train.py, choose a model, "
        "and review its performance on the held-out test set."
    )

    uploaded_file = st.file_uploader("Upload test_data.csv", type=["csv"])
    model_display_name = st.selectbox("Select a model", list(MODEL_FILES.keys()))

    if uploaded_file is None:
        st.info("Waiting for a test_data.csv upload.")
        return

    raw_df = pd.read_csv(uploaded_file)

    if TARGET_COLUMN not in raw_df.columns:
        st.error(f"Uploaded file must contain the '{TARGET_COLUMN}' column.")
        return

    scaler, encoders, target_encoder, feature_columns, numeric_columns = (
        load_preprocessing_objects()
    )
    model = load_model(MODEL_FILES[model_display_name])

    X = preprocess(raw_df, encoders, scaler, feature_columns, numeric_columns)
    y_true = target_encoder.transform(raw_df[TARGET_COLUMN])

    y_pred = model.predict(X)
    if hasattr(model, "predict_proba"):
        y_score = model.predict_proba(X)[:, 1]
    else:
        y_score = y_pred

    metrics = {
        "Accuracy": accuracy_score(y_true, y_pred),
        "AUC": roc_auc_score(y_true, y_score),
        "Precision": precision_score(y_true, y_pred),
        "Recall": recall_score(y_true, y_pred),
        "F1": f1_score(y_true, y_pred),
        "MCC": matthews_corrcoef(y_true, y_pred),
    }

    st.subheader(f"Evaluation Metrics - {model_display_name}")
    metric_columns = st.columns(len(metrics))
    for column, (metric_name, value) in zip(metric_columns, metrics.items()):
        column.metric(metric_name, f"{value:.4f}")

    col_left, col_right = st.columns(2)

    with col_left:
        st.subheader("Confusion Matrix")
        cm = confusion_matrix(y_true, y_pred)
        fig, ax = plt.subplots(figsize=(4, 3.5))
        sns.heatmap(
            cm,
            annot=True,
            fmt="d",
            cmap="Blues",
            xticklabels=target_encoder.classes_,
            yticklabels=target_encoder.classes_,
            ax=ax,
        )
        ax.set_xlabel("Predicted")
        ax.set_ylabel("Actual")
        st.pyplot(fig)

    with col_right:
        st.subheader("Classification Report")
        report = classification_report(
            y_true,
            y_pred,
            target_names=target_encoder.classes_,
            output_dict=True,
        )
        report_df = pd.DataFrame(report).transpose()
        st.dataframe(report_df.style.format("{:.4f}"))


if __name__ == "__main__":
    main()
